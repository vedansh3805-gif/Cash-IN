    setCurrency(code) {
        this.currencyCode = code;
        const symbols = { INR: '₹', USD: '$', EUR: '€', GBP: '£' };
        this.currencySymbol = symbols[code] || code;
    },

    formatCurrency(amount) {
        if (amount == null || isNaN(amount)) return `${this.currencySymbol}0`;
        const num = Number(amount);
        const isNeg = num < 0;
        if (this.currencyCode === 'INR') {
            return (isNeg ? '-' : '') + this.currencySymbol + this.formatIndianNumber(Math.abs(num), false);
        }
        const formatted = Math.abs(num).toLocaleString('en-US', {
            minimumFractionDigits: 0,
            maximumFractionDigits: 0,
        });
        return (isNeg ? '-' : '') + this.currencySymbol + formatted;
    },

    formatIndianNumber(num, negative = false) {
        const str = Math.round(num).toString();
        let result;
        if (str.length <= 3) {
            result = str;
        } else {
            const last3 = str.slice(-3);
            const rest = str.slice(0, -3);
            const parts = [];
            for (let i = rest.length; i > 0; i -= 2) {
                parts.unshift(rest.slice(Math.max(0, i - 2), i));
            }
            result = parts.join(',') + ',' + last3;
        }
        return (negative ? '-' : '') + result;
    },

    formatDate(dateStr) {
        if (!dateStr) return '—';
        const date = new Date(dateStr);
        if (isNaN(date)) return dateStr;
        return date.toLocaleDateString('en-IN', {
            day: '2-digit',
            month: 'short',
            year: 'numeric',
        });
    },

    formatDateShort(dateStr) {
        if (!dateStr) return '—';
        const date = new Date(dateStr);
        if (isNaN(date)) return dateStr;
        return date.toLocaleDateString('en-IN', {
            day: '2-digit',
            month: 'short',
        });
    },

    formatDateISO(date) {
        if (!date) return '';
        const d = new Date(date);
        return isNaN(d) ? '' : d.toISOString().split('T')[0];
    },

    statusBadge(status) {
        if (!status) return '';
        const s = String(status).toUpperCase();
        let cls = 'badge-secondary';
        let dot = '#94a3b8';

        if (s === 'PAID' || s === 'ADDED' || s === 'LOW' || s === 'ACTIVE') {
            cls = 'badge-success';
            dot = '#10b981';
        } else if (s === 'PENDING' || s === 'MODIFIED' || s === 'MODERATE' || s === 'WARNING') {
            cls = 'badge-warning';
            dot = '#f59e0b';
        } else if (s === 'OVERDUE' || s === 'REMOVED' || s === 'HIGH' || s === 'CRITICAL') {
            cls = 'badge-danger';
            dot = '#ef4444';
        } else if (s === 'UNCHANGED' || s === 'INFO') {
            cls = 'badge-info';
            dot = '#38bdf8';
        }

        return `<span class="badge ${cls}"><span class="badge-dot" style="background:${dot}"></span>${s}</span>`;
    },

    showToast(message, type = 'info', duration = 3500) {
        let container = document.getElementById('toast-container');
        if (!container) {
            container = document.createElement('div');
            container.id = 'toast-container';
            container.className = 'toast-container';
            document.body.appendChild(container);
        }
        const toast = document.createElement('div');
        toast.className = `toast ${type}`;
        toast.innerHTML = `<span class="toast-message">${this.escapeHtml(message)}</span>`;
        container.appendChild(toast);
        setTimeout(() => {
            toast.style.opacity = '0';
            toast.style.transform = 'translateY(-8px)';
            toast.style.transition = 'all 0.25s ease';
            setTimeout(() => toast.remove(), 260);
        }, duration);
    },

    daysOverdue(dueDate) {
        if (!dueDate) return 0;
        const due = new Date(dueDate);
        const today = new Date();
        const diff = Math.floor((today - due) / (1000 * 60 * 60 * 24));
        return Math.max(0, diff);
    },

    escapeHtml(text) {
        if (!text) return '';
        const div = document.createElement('div');
        div.textContent = text;
        return div.innerHTML;
    },

    truncate(text, maxLen = 40) {
        if (!text || text.length <= maxLen) return text || '';
        return text.substring(0, maxLen) + '…';
    },
